/// Whether `token` (already lowercased) is a stopword.
#[must_use]
pub fn is_stopword(token: &str) -> bool {
    STOPWORDS.binary_search(&token).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_sorted_and_unique() {
        assert!(STOPWORDS.windows(2).all(|w| w.first() < w.get(1)));
    }

    #[test]
    fn known_words() {
        assert!(is_stopword("the"));
        assert!(is_stopword("don't"));
        assert!(is_stopword("one"));
        assert!(is_stopword("who"));
        assert!(!is_stopword("rust"));
        assert!(!is_stopword(""));
    }
}
